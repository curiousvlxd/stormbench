from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from . import paper
from .kpi import EVENT_GAP_S, SPILL_EPS_M3, point_kpis, total_row, write_csv
from .network import Network
from .runner import RunResult


def _pct(new: float, old: float) -> str:
    return f"{(new / old - 1) * 100:+.2f}%"


def _report_total(run: RunResult) -> float:
    return float(sum(run.totals["report_flood_m3"].values()))


def reproduction_table(bc: RunResult, efd_swmm: RunResult, efd_plc: RunResult | None) -> str:
    columns = [
        ("Paper BC", paper.SWMM_BC),
        ("Ours BC", bc.totals["report_flood_m3"]),
        ("Paper EFD", paper.SWMM_EFD),
        ("Ours EFD, SWMM rules", efd_swmm.totals["report_flood_m3"]),
    ]
    if efd_plc is not None:
        columns.append(("Ours EFD, PLC", efd_plc.totals["report_flood_m3"]))
    lines = ["| Point | " + " | ".join(c[0] for c in columns) + " |", "|---|" + "---:|" * len(columns)]
    for point in paper.POINTS:
        lines.append(f"| {point} | " + " | ".join(f"{c[1][point]:,.0f}" for c in columns) + " |")
    totals = [float(sum(c[1].values())) for c in columns]
    totals[0], totals[2] = paper.SWMM_BC_TOTAL, paper.SWMM_EFD_TOTAL
    lines.append("| **Total** | " + " | ".join(f"**{t:,.0f}**" for t in totals) + " |")
    changes = ["", "", _pct(totals[2], totals[0]), _pct(totals[3], totals[1])]
    if efd_plc is not None:
        changes.append(_pct(totals[4], totals[1]))
    lines.append("| EFD vs BC | " + " | ".join(changes) + " |")
    return "\n".join(lines)


def plc_vs_python(py: RunResult, plc: RunResult, points: tuple[str, ...]) -> dict:
    same_len = py.times_s.shape == plc.times_s.shape
    volume_diff = {p: float(abs(plc.totals["flood_m3"][p] - py.totals["flood_m3"][p])) for p in points}
    return {
        "steps": int(plc.times_s.size),
        "same_time_axis": bool(same_len and np.array_equal(py.times_s, plc.times_s)),
        "identical_setpoints": bool(same_len and np.array_equal(py.setpoints, plc.setpoints)),
        "identical_depths": bool(same_len and np.array_equal(py.depths, plc.depths)),
        "identical_status": bool(
            same_len
            and np.array_equal(py.status, plc.status)
            and np.array_equal(py.mode_active, plc.mode_active)
        ),
        "max_volume_diff_m3": max(volume_diff.values()),
        "total_volume_diff_m3": float(abs(plc.totals["flood_total_m3"] - py.totals["flood_total_m3"])),
        "shadow_mismatches": plc.meta.get("shadow_mismatches"),
    }


def write_report(runs: dict[str, RunResult], net: Network, out_dir: Path) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    bc, efd_swmm = runs["bc"], runs["efd-swmm"]
    efd_py, efd_plc = runs.get("efd-python"), runs.get("efd-plc")
    kpis = {name: point_kpis(run, net.overflow_points) for name, run in runs.items()}
    write_csv(out_dir / "kpi.csv", kpis)

    summary: dict = {
        "paper": {
            "bc_total_m3": paper.SWMM_BC_TOTAL,
            "efd_total_m3": paper.SWMM_EFD_TOTAL,
            "efd_reduction_pct": paper.SWMM_EFD_REDUCTION_PCT,
        },
        "runs": {
            name: {
                "report_total_m3": round(_report_total(run), 1),
                "api_total_m3": round(run.totals["flood_total_m3"], 1),
                "wwtp_inflow_m3": round(run.totals["wwtp_inflow_m3"], 1),
                "events": total_row(kpis[name]).events,
                "spill_hours": round(total_row(kpis[name]).spill_hours, 2),
                "wall_s": run.meta.get("wall_s"),
            }
            for name, run in runs.items()
        },
    }
    lines = [
        "# Validation results",
        "",
        "Generated by `python -m stormbench_sim report`. Astlingen benchmark, rain year 2000, EPA SWMM 5.2.4 "
        "(swmm-toolkit 0.17.0). Paper: Sun et al. (2020), Water 12(4), 1034, Tables 4 and 5, EPA SWMM 5.1.013.",
        "",
        "## 1. Reproduction of the paper (overflow volume in m³, SWMM report values)",
        "",
        reproduction_table(bc, efd_swmm, efd_plc),
        "",
        "Differences to the paper are a few m³ per point. The paper's CSO10 value under EFD (4,751) is a typo "
        "for 4,741: CSO10 lies upstream of every controlled outlet, so control cannot change it, and the "
        "paper's own EFD total (247,788) only adds up with 4,741 (with 4,751 the column sums to 247,798).",
        "",
    ]
    if efd_py is not None and efd_plc is not None:
        check = plc_vs_python(efd_py, efd_plc, net.overflow_points)
        summary["plc_vs_python"] = check
        link = efd_plc.meta.get("plc", {})
        verdict = (
            "identical"
            if check["identical_setpoints"]
            and check["identical_depths"]
            and check["total_volume_diff_m3"] == 0.0
            else "DIFFERENT"
        )
        lines += [
            "## 2. EFD on the PLC vs the Python reference",
            "",
            f"Result: **{verdict}**.",
            "",
            "| Check | Value |",
            "|---|---|",
            f"| Control steps (5 min) | {check['steps']:,} |",
            f"| Setpoint time series identical | {check['identical_setpoints']} |",
            f"| Tank level time series identical | {check['identical_depths']} |",
            f"| Mode and status words identical | {check['identical_status']} |",
            f"| Steps where the PLC answer differed from the shadow Python decision | {check['shadow_mismatches']} |",
            f"| Largest per-point volume difference | {check['max_volume_diff_m3']:.3f} m³ |",
            f"| PLC exchanges, polls | {link.get('exchanges', 0):,}, {link.get('polls', 0):,} |",
            f"| Wall time of the PLC run | {efd_plc.meta.get('wall_s')} s |",
            "",
        ]
    variants = [(n, r) for n, r in runs.items() if n.startswith("efd")]
    lines += [
        "## 3. Control variants",
        "",
        "| Run | Controller | Mode | Overflow (report) m³ | vs Base Case | Events | Spill hours "
        "| Inflow to WWTP m³ |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for name, run in [("bc", bc), *variants]:
        k = total_row(kpis[name])
        lines.append(
            f"| {name} | {run.controller} | {run.mode.name} | {_report_total(run):,.0f} | "
            f"{_pct(_report_total(run), _report_total(bc))} | {k.events} | {k.spill_hours:.1f} "
            f"| {run.totals['wwtp_inflow_m3']:,.0f} |"
        )
    lines += [
        "",
        f"Events: intervals with more than {SPILL_EPS_M3} m³ overflow, merged when less than "
        f"{EVENT_GAP_S // 60} min apart, counted per overflow point and summed. `EFD_PUBLISHED` is "
        "`EFD_Control.txt` as SWMM executes it; `EFD_INTENDED` applies the fix from SWMM-Astlingen PR #1 "
        "(rule priorities, 1 m threshold, throttling of the emptiest tank).",
        "",
        "## 4. Per-point KPIs",
        "",
        "See `kpi.csv` (volume from SWMM's cumulative statistics, events, spill hours, SWMM hours flooded).",
        "",
    ]
    (out_dir / "validation.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8", newline="\n")
    return summary
