from __future__ import annotations

import argparse
import json
import os
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from . import paper
from .control import Mode
from .network import read_period
from .pipeline import execute_offline
from .runner import RunResult
from .service import STORMS, Storm, storm_period

STRATEGIES = (
    ("bc", "swmm-base", Mode.LOCAL, "uns", None),
    ("efd", "python", Mode.EFD_PUBLISHED, "uns", None),
    ("mpc", "python", Mode.EFD_CENTER, "mpc", "perfect"),
    ("mpc-persistence", "python", Mode.EFD_CENTER, "mpc", "persistence"),
)


def run_name(storm: Storm, strategy: str) -> str:
    return f"compare-{storm.id}-{strategy}"


def windows(year: bool) -> list[Storm]:
    return [s for s in STORMS if year or s.period is not None]


def run_all(args: argparse.Namespace, storms: list[Storm]) -> dict[str, dict[str, RunResult]]:
    from .network import load_network

    net = load_network(args.network, Path(args.model_dir))
    model_period = read_period(net)
    base = {k: v for k, v in vars(args).items() if k != "func"}
    base.update(pace=0.0, outage=None, center_variant="efd-published")
    jobs = []
    for storm in storms:
        start, end = storm_period(storm, model_period)
        for strategy, control, mode, center, forecast in STRATEGIES:
            arg_dict = dict(
                base, start=start.isoformat(), end=end.isoformat(), center=center, mpc_forecast=forecast
            )
            jobs.append((run_name(storm, strategy), control, int(mode), arg_dict))
    jobs.sort(key=lambda job: (job[3]["start"] != model_period[0].isoformat() or job[1] != "python", job[0]))
    workers = max(1, min(len(jobs), args.jobs or (os.cpu_count() or 1)))
    with ProcessPoolExecutor(max_workers=workers) as pool:
        for name in pool.map(execute_offline, jobs):
            print("done:", name)
    runs_dir = Path(args.results_dir) / "runs"
    return {
        storm.id: {s[0]: RunResult.load(runs_dir / run_name(storm, s[0])) for s in STRATEGIES}
        for storm in storms
    }


def _pct(new: float, old: float) -> float:
    return (new / old - 1.0) * 100.0


def summarise(storms: list[Storm], runs: dict[str, dict[str, RunResult]]) -> dict:
    rows = []
    for storm in storms:
        r = runs[storm.id]
        totals = {k: float(v.totals["flood_total_m3"]) for k, v in r.items()}
        rows.append(
            {
                "storm": storm.id,
                "label": storm.label,
                "steps": int(r["mpc"].meta["steps"]),
                "total_m3": totals,
                "change_pct": {k: _pct(totals[k], totals["bc"]) for k in totals if k != "bc"},
                "report_flood_m3": {k: v.totals["report_flood_m3"] for k, v in r.items()},
                "flood_m3": {k: v.totals["flood_m3"] for k, v in r.items()},
                "wwtp_inflow_m3": {k: float(v.totals["wwtp_inflow_m3"]) for k, v in r.items()},
                "mpc_solver": r["mpc"].meta.get("mpc", {}),
                "wall_s": {k: v.meta["wall_s"] for k, v in r.items()},
            }
        )
    return {"rows": rows}


def write_table(summary: dict, results_dir: Path) -> str:
    lines = [
        "# Control strategies compared offline",
        "",
        "Generated by `python -m stormbench_sim compare --year`. Python only, no PLC: Base Case (SWMM "
        "rules), EFD as SWMM executes it (the Python reference, which takes the same decisions as the "
        "PLC), and MPC (`stormbench_sim/mpc.py`: a linear program per 5 min step, horizon 100 min, its "
        "proposals checked by the Python reference of the PLC stations in mode 3). MPC uses a perfect "
        "forecast of the inflows no control changes; *MPC, no forecast* holds the last measured inflow "
        "over the horizon instead. Overflow volume in m³ from the SWMM node flooding statistics, each "
        "window started with empty tanks. See ADR 0017.",
        "",
        "| Storm | Base Case | EFD | MPC | MPC, no forecast | LP solve, mean / p99 / max |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for row in summary["rows"]:
        t, c, s = row["total_m3"], row["change_pct"], row["mpc_solver"]
        cells = [f"{t['bc']:,.0f} m³"] + [
            f"{t[k]:,.0f} m³ ({c[k]:+.1f}%)" for k in ("efd", "mpc", "mpc-persistence")
        ]
        lines.append(
            f"| {row['label']} | "
            + " | ".join(cells)
            + f" | {s.get('mean_ms', 0):.1f} / {s.get('p99_ms', 0):.1f} / {s.get('max_ms', 0):.1f} ms |"
        )
    year = next((r for r in summary["rows"] if r["storm"] == "2000"), None)
    if year is not None:
        rep = year["report_flood_m3"]
        tot = {k: float(sum(v.values())) for k, v in rep.items()}
        lines += [
            "",
            "## The rain year next to the paper",
            "",
            "SWMM report values, as in `validation.md`. Paper: Sun et al. (2020), Tables 4 to 6, EPA "
            "SWMM 5.1.013; its MPC ran in MATLAB with Mosek (quadratic program) on a conceptual internal "
            "model, 5 min step, 100 min horizon, perfect forecast.",
            "",
            "| Point | Paper BC | Ours BC | Paper EFD | Ours EFD | Paper MPC | Ours MPC | Ours MPC, no forecast |",
            "|---|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for point in paper.POINTS:
            lines.append(
                f"| {point} | {paper.SWMM_BC[point]:,.0f} | {rep['bc'][point]:,.0f} "
                f"| {paper.SWMM_EFD[point]:,.0f} | {rep['efd'][point]:,.0f} "
                f"| {paper.SWMM_MPC[point]:,.0f} | {rep['mpc'][point]:,.0f} | {rep['mpc-persistence'][point]:,.0f} |"
            )
        lines.append(
            f"| **Total** | **{paper.SWMM_BC_TOTAL:,.0f}** | **{tot['bc']:,.0f}** | **{paper.SWMM_EFD_TOTAL:,.0f}** "
            f"| **{tot['efd']:,.0f}** | **{paper.SWMM_MPC_TOTAL:,.0f}** | **{tot['mpc']:,.0f}** "
            f"| **{tot['mpc-persistence']:,.0f}** |"
        )
        lines.append(
            f"| vs BC | | | {_pct(paper.SWMM_EFD_TOTAL, paper.SWMM_BC_TOTAL):+.2f}% | {_pct(tot['efd'], tot['bc']):+.2f}% "
            f"| {_pct(paper.SWMM_MPC_TOTAL, paper.SWMM_BC_TOTAL):+.2f}% | {_pct(tot['mpc'], tot['bc']):+.2f}% "
            f"| {_pct(tot['mpc-persistence'], tot['bc']):+.2f}% |"
        )
        wwtp = year["wwtp_inflow_m3"]
        lines += [
            "",
            f"Water is conserved: MPC spills {tot['bc'] - tot['mpc']:,.0f} m³ less than the Base Case and "
            f"sends {wwtp['mpc'] - wwtp['bc']:,.0f} m³ more to the treatment plant. "
            f"Wall time of the MPC year: {year['wall_s']['mpc']:,.0f} s for {year['steps']:,} steps.",
        ]
    text = "\n".join(lines) + "\n"
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "controllers.md").write_text(text, encoding="utf-8", newline="\n")
    (results_dir / "controllers.json").write_text(
        json.dumps(summary, indent=2, default=str) + "\n", encoding="utf-8", newline="\n"
    )
    return text


def cmd_compare(args: argparse.Namespace) -> int:
    storms = windows(args.year)
    if args.storm:
        storms = [s for s in storms if s.id in args.storm]
    if not args.report_only:
        run_all(args, storms)
    runs_dir = Path(args.results_dir) / "runs"
    runs = {
        storm.id: {s[0]: RunResult.load(runs_dir / run_name(storm, s[0])) for s in STRATEGIES}
        for storm in storms
    }
    print(write_table(summarise(storms, runs), Path(args.results_dir)))
    return 0
